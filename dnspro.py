#!/usr/bin/env python3
"""DNSPro CLI — set or restore system DNS on Linux."""

import os
import shutil
import sys

DNSPRO_DNS = "80.244.11.244"
RESOLV_CONF = "/etc/resolv.conf"
BACKUP_PATH = "/etc/resolv.conf.dnspro.bak"
VERSION = "1.0.0"


def is_root():
    return os.geteuid() == 0


def require_root():
    if not is_root():
        print("Error: this command requires root. Re-run with sudo.")
        sys.exit(1)


def cmd_set():
    require_root()

    if not os.path.exists(RESOLV_CONF):
        print(f"Error: {RESOLV_CONF} not found.")
        sys.exit(1)

    if not os.path.exists(BACKUP_PATH):
        shutil.copy2(RESOLV_CONF, BACKUP_PATH)
        print(f"Backup saved to {BACKUP_PATH}")
    else:
        print(f"Backup already exists at {BACKUP_PATH}")

    content = (
        f"# Generated by DNSPro CLI\n"
        f"nameserver {DNSPRO_DNS}\n"
    )

    # Replace symlink with a real file so our settings stick.
    if os.path.islink(RESOLV_CONF):
        os.remove(RESOLV_CONF)

    with open(RESOLV_CONF, "w", encoding="utf-8") as f:
        f.write(content)

    print(f"DNS set to DNSPro ({DNSPRO_DNS})")


def cmd_rollback():
    require_root()

    if not os.path.exists(BACKUP_PATH):
        print(f"Error: no backup found at {BACKUP_PATH}")
        sys.exit(1)

    if os.path.islink(RESOLV_CONF):
        os.remove(RESOLV_CONF)

    shutil.copy2(BACKUP_PATH, RESOLV_CONF)
    os.remove(BACKUP_PATH)
    print("DNS restored from backup.")


def cmd_status():
    print(f"DNSPro CLI v{VERSION}")
    print(f"Target DNS: {DNSPRO_DNS}")
    print(f"Backup: {'yes' if os.path.exists(BACKUP_PATH) else 'no'}")
    print()

    if not os.path.exists(RESOLV_CONF):
        print(f"{RESOLV_CONF} not found.")
        return

    print("Current nameservers:")
    found = False
    with open(RESOLV_CONF, "r", encoding="utf-8", errors="replace") as f:
        for line in f:
            stripped = line.strip()
            if stripped.startswith("nameserver"):
                print(f"  {stripped}")
                found = True
    if not found:
        print("  (none)")


def usage():
    print(
        "Usage:\n"
        "  sudo python3 dnspro.py set       Set DNS to DNSPro\n"
        "  sudo python3 dnspro.py rollback  Restore previous DNS\n"
        "  python3 dnspro.py status         Show current DNS\n"
        "  python3 dnspro.py version        Show version"
    )


def main():
    if len(sys.argv) != 2:
        usage()
        sys.exit(1)

    command = sys.argv[1].lower()

    if command == "set":
        cmd_set()
    elif command == "rollback":
        cmd_rollback()
    elif command == "status":
        cmd_status()
    elif command == "version":
        print(VERSION)
    elif command in ("-h", "--help", "help"):
        usage()
    else:
        print(f"Unknown command: {command}\n")
        usage()
        sys.exit(1)


if __name__ == "__main__":
    main()
